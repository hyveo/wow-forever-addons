ns.LANGS = { "koKR", "enUS", "deDE", "esMX", "esES", "frFR", "ptBR", "ruRU", "zhCN", "zhTW" }
ns.LANG_NAMES = {
	koKR = "한국어", enUS = "English", deDE = "Deutsch",
	esMX = "Español (América Latina)", esES = "Español (España)",
	frFR = "Français", ptBR = "Português", ruRU = "Русский",
	zhCN = "简体中文", zhTW = "繁體中文",
}

-- 두 파일이 같은 표를 계속 쓰도록, 언어를 바꿀 때는 표를 새로 만들지 않고 내용만 바꾼다
local L, L2 = {}, {}
ns.L, ns.L2 = L, L2

local function Fill(dst, part, code)
	wipe(dst)
	local chain = { "enUS" }
	if code == "esMX" then chain[#chain + 1] = "esES" end
	if code ~= "enUS" then chain[#chain + 1] = code end
	for _, c in ipairs(chain) do
		for k, v in pairs(S[c][part]) do dst[k] = v end
	end
end

function ns.GameLocale()
	local g = GetLocale()
	if g == "enGB" then g = "enUS" end
	return g
end

-- choice: nil 또는 "auto" = 게임 언어, 아니면 언어 코드
function ns.ApplyLocale(choice)
	local code = (choice and choice ~= "auto" and S[choice]) and choice or ns.GameLocale()
	if not S[code] then code = "enUS" end
	ns.locale = code
	Fill(L, "main", code)
	Fill(L2, "opt", code)
end

ns.ApplyLocale()
